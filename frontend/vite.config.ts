import { defineConfig, type Plugin } from 'vitest/config';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';

// Dev proxy keeps the SPA same-origin with the API so session cookies and CSRF
// behave exactly as they do in production behind Nginx. Override the target when
// the API runs on a non-default port (API_PROXY_TARGET=http://localhost:8081).
const apiTarget = process.env.API_PROXY_TARGET ?? 'http://localhost:8080';

// Vite substitutes %VITE_SITE_URL% in index.html only when the variable exists;
// default it to an empty string so builds without a .env (CI) resolve the
// placeholder silently to origin-relative URLs. Production exports the real
// origin (see .env.example) and gets absolute canonical/OG URLs instead.
// Normalized once here so Vite's own env replacement and the post-transform
// below both see the same slash-free origin (no "https://origin//" in tags).
process.env.VITE_SITE_URL = (process.env.VITE_SITE_URL ?? '').replace(/\/+$/, '');

/**
 * index.html carries %VITE_SITE_URL% placeholders so canonical/Open Graph URLs
 * can be absolute in production. Vite only substitutes variables that actually
 * exist in the environment; this post-transform guarantees the placeholder
 * always resolves (empty string when unset) instead of leaking the literal
 * token into dist/index.html. Same value source as Vite's own env resolution.
 */
function htmlSiteUrl(): Plugin {
  return {
    name: 'codepath-html-site-url',
    transformIndexHtml: {
      order: 'post',
      handler(html) {
        const siteUrl = (process.env.VITE_SITE_URL ?? '').replace(/\/+$/, '');
        const resolved = html.replace(/%VITE_SITE_URL%/g, siteUrl);
        if (!siteUrl) return resolved;
        // Root canonical reads better with a trailing slash (matches og:url).
        return resolved.replace(
          `rel="canonical" href="${siteUrl}"`,
          `rel="canonical" href="${siteUrl}/"`,
        );
      },
    },
  };
}

export default defineConfig({
  plugins: [react(), tailwindcss(), htmlSiteUrl()],
  server: {
    port: 5173,
    proxy: {
      '/api': {
        target: apiTarget,
        changeOrigin: false,
      },
      '/actuator': {
        target: apiTarget,
        changeOrigin: false,
      },
      // Crawler files are generated by the backend (SeoController) so dev and
      // the container edge expose identical robots/sitemap behavior.
      '/robots.txt': {
        target: apiTarget,
        changeOrigin: false,
      },
      '/sitemap.xml': {
        target: apiTarget,
        changeOrigin: false,
      },
    },
  },
  test: {
    globals: true,
    environment: 'jsdom',
    setupFiles: ['./src/test/setup.ts'],
    css: false,
  },
});
